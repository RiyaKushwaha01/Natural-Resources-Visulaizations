-- 16. Categorize the states into high and low revenue (TOP 5 & BOTTOM 5)
WITH TOT_REVENUE AS (
	SELECT State,
	SUM(Revenue) AS TOT_REVENUE
	FROM calendar_year_revenue
	GROUP BY State
), 
RANKED_STATES AS (
	SELECT State,
	TOT_REVENUE,
	RANK() OVER (ORDER BY TOT_REVENUE DESC) AS RANK_DESC,
	RANK() OVER (ORDER BY TOT_REVENUE ASC) AS RANK_ASC
	FROM TOT_REVENUE
),
CLASSIFIED_STATES AS (
	SELECT State,
	TOT_REVENUE,
	CASE 
		WHEN RANK_DESC <= 5 THEN 'HIGH'
		WHEN RANK_ASC <= 5 THEN 'LOW'
		ELSE 'MID'
	END AS REVENUE_GROUP
	FROM RANKED_STATES
)
SELECT * 
FROM CLASSIFIED_STATES
ORDER BY REVENUE_GROUP, TOT_REVENUE DESC


