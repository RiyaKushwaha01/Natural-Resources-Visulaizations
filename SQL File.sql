-- 10. YOY Chnage (FOR GROWTH)
SELECT Calendar_Year,
Commodity,
SUM(Revenue) AS REVENUE,
LAG(SUM(Revenue)) OVER (PARTITION BY Commodity ORDER BY Calendar_Year) AS PREV_YEAR_REVENUE,
SUM(Revenue) - LAG(SUM(Revenue)) OVER (PARTITION BY Commodity ORDER BY Calendar_Year) AS REVENUE_CHANGE,
CASE
	WHEN LAG(SUM(Revenue)) OVER (PARTITION BY Commodity ORDER BY Calendar_Year) = 0 THEN NULL
	ELSE ROUND (
	(SUM(Revenue) - LAG(SUM(Revenue)) OVER (PARTITION BY Commodity ORDER BY Calendar_Year)) * 100.0 / 
	LAG(SUM(Revenue)) OVER (PARTITION BY Commodity ORDER BY Calendar_Year), 2 )
END AS YOY_CHANGE
FROM calendar_year_revenue
GROUP BY Calendar_Year, Commodity
ORDER BY Commodity, Calendar_Year
 


-- 11. Impact of Different Commodities on Revenue Drop/Growth
WITH REVENUE_BY_YEAR AS (
	SELECT Calendar_Year, Commodity,
	SUM(Revenue) AS REVENUE
	FROM calendar_year_revenue
	GROUP BY Calendar_Year, Commodity
),
REVENUE_CHANGE AS ( 
	SELECT Calendar_Year,
	Commodity,
	REVENUE,
	LAG(REVENUE) OVER (PARTITION BY Commodity ORDER BY Calendar_Year) AS PREV_YEAR_REVENUE,
	(REVENUE - LAG(REVENUE) OVER (PARTITION BY Commodity ORDER BY Calendar_Year) ) AS REVENUE_CHANGE
	FROM REVENUE_BY_YEAR
)

SELECT Calendar_Year,
Commodity,
REVENUE,
PREV_YEAR_REVENUE,
CASE 
	WHEN PREV_YEAR_REVENUE = 0 THEN NULL
	ELSE ROUND (
	(REVENUE - PREV_YEAR_REVENUE) * 100.0 / 
	PREV_YEAR_REVENUE, 2) 
END AS YOY_CHANGE,
CASE 
	WHEN REVENUE > PREV_YEAR_REVENUE THEN 'GROWTH'
	WHEN REVENUE < PREV_YEAR_REVENUE THEN 'DROP'
	ELSE 'NO CHNAGE'
END AS IMPACT
FROM REVENUE_CHANGE
ORDER BY Calendar_Year, Commodity


