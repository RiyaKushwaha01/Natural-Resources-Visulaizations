-- 17. Identify states with consistent YoY growth
WITH REVENUE_BY_YEAR AS (
	SELECT Calendar_Year, State,
	SUM(Revenue) AS REVENUE
	FROM calendar_year_revenue
	GROUP BY Calendar_Year, State
),
PREV_YEAR_REVENUE AS ( 
	SELECT Calendar_Year,
	State,
	REVENUE,
	LAG(REVENUE) OVER (PARTITION BY State ORDER BY Calendar_Year) AS PREV_YEAR_REVENUE
	FROM REVENUE_BY_YEAR
),

REVENUE_CHANGE AS ( 
	SELECT Calendar_Year,
	State,
	REVENUE, 
	PREV_YEAR_REVENUE,
	(REVENUE - PREV_YEAR_REVENUE) AS REVENUE_CHANGE
	FROM PREV_YEAR_REVENUE
	WHERE PREV_YEAR_REVENUE IS NOT NULL
),
CONSISTENT_STATE_GROWTH AS (
	SELECT State
	FROM REVENUE_CHANGE
	GROUP BY state
    HAVING MIN(revenue_change) > 0
)
SELECT R.*
FROM REVENUE_CHANGE AS R
JOIN CONSISTENT_STATE_GROWTH AS C 
ON R.state = C.state
ORDER BY R.state, R.Calendar_Year

